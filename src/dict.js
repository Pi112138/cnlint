/**
 * 取出去重后的有效词条（剔除错词与正词相同的无效条目）。
 * @returns {Array<{wrong: string, right: string}>}
 */
export function getTypoEntries() {
  const entries = [];
  for (const [wrong, right] of Object.entries(typoDict)) {
    if (!wrong || !right) continue;
    if (wrong === right) continue;
    entries.push({ wrong, right });
  }
  // 长词优先匹配，避免「按装」先命中「按装置」之类
  entries.sort((a, b) => b.wrong.length - a.wrong.length);
  return entries;
}
